  // 32×32 native bitmaps for 64×64 px Hero Play / Pause (exact 2px/dot!)
  const BITMAPS_32 = {
    'ic-play': Array.from({ length: 32 }, (_, y) => {
      if (y < 4 || y > 27) return '.'.repeat(32);
      const dist = Math.abs(y - 15.5);
      const width = Math.max(2, Math.round((12.5 - dist) * 1.75));
      const w = Math.min(22, width);
      return '.'.repeat(7) + '#'.repeat(w) + '.'.repeat(32 - 7 - w);
    }),
    'ic-pause': Array.from({ length: 32 }, (_, y) => {
      if (y < 5 || y > 26) return '.'.repeat(32);
      return '......######........######......';
    }),
    'ic-shuffle': (() => {
      const g = Array.from({ length: 32 }, () => Array(32).fill('.'));
      const dot = (x, y) => {
        if (x >= 0 && x < 32 && y >= 0 && y < 32) g[y][x] = '#';
      };
      const thickLine = (x0, y0, x1, y1) => {
        const steps = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0)) * 2;
        for (let i = 0; i <= steps; i++) {
          const x = Math.round(x0 + ((x1 - x0) * i) / steps);
          const y = Math.round(y0 + ((y1 - y0) * i) / steps);
          for (let dx = -1; dx <= 1; dx++) {
            for (let dy = -1; dy <= 1; dy++) dot(x + dx, y + dy);
          }
        }
      };
      // Lower-left to upper-right crossing path
      thickLine(3, 22, 10, 22);
      thickLine(10, 22, 20, 9);
      thickLine(20, 9, 27, 9);
      // Upper-left to lower-right path (with crisp crossing gap in center)
      thickLine(3, 9, 10, 9);
      thickLine(10, 9, 13, 13);
      thickLine(17, 18, 20, 22);
      thickLine(20, 22, 27, 22);
      // Right arrowheads (top at y=9, bottom at y=22)
      [9, 22].forEach((cy) => {
        for (let dy = -4; dy <= 4; dy++) {
          const span = 4 - Math.abs(dy);
          for (let dx = 0; dx <= span; dx++) dot(24 + dx, cy + dy);
        }
      });
      return g.map((r) => r.join(''));
    })(),
  };

  function buildSymbol(svgNS, id, rows) {
    const size = rows.length;
    const sym = document.createElementNS(svgNS, 'symbol');
    sym.setAttribute('id', id);
    sym.setAttribute('viewBox', `0 0 ${size} ${size}`);
    sym.setAttribute('shape-rendering', 'crispEdges');

    let d = '';
    for (let y = 0; y < size; y++) {
      const line = rows[y];
      for (let x = 0; x < line.length; x++) {
        if (line[x] === '#') {
          d += `M${x} ${y}h1v1h-1z`;
        }
      }
    }
    const path = document.createElementNS(svgNS, 'path');
    path.setAttribute('d', d);
    path.setAttribute('fill', 'currentColor');
    sym.appendChild(path);
    return sym;
  }

  function injectVfdSprite() {
    const svgNS = 'http://www.w3.org/2000/svg';
    const hostSvg = document.querySelector('svg[aria-hidden="true"]');
    if (!hostSvg) return;

    Object.entries(BITMAPS_8).forEach(([id, rows]) => hostSvg.appendChild(buildSymbol(svgNS, `vfd8-${id}`, rows)));
    Object.entries(BITMAPS_16).forEach(([id, rows]) => hostSvg.appendChild(buildSymbol(svgNS, `vfd16-${id}`, rows)));
    Object.entries(BITMAPS_24).forEach(([id, rows]) => hostSvg.appendChild(buildSymbol(svgNS, `vfd24-${id}`, rows)));
    Object.entries(BITMAPS_32).forEach(([id, rows]) => hostSvg.appendChild(buildSymbol(svgNS, `vfd32-${id}`, rows)));
  }

  function resolveVfdTarget(useEl, baseId) {
    const svg = useEl.closest('svg');
    if (svg) {
      if (svg.classList.contains('hero-ic') && BITMAPS_32[baseId]) return `#vfd32-${baseId}`;
      if ((svg.classList.contains('pad-ic-lg') || svg.classList.contains('transport-ic')) && BITMAPS_24[baseId]) return `#vfd24-${baseId}`;
      if (svg.classList.contains('ic-16') && BITMAPS_8[baseId]) return `#vfd8-${baseId}`;
    }
    return BITMAPS_16[baseId] ? `#vfd16-${baseId}` : `#${baseId}`;
  }

  function applyVfdIcons(root, isVfd) {
    if (!root) return;
    const uses = root.querySelectorAll('use[href]');
    uses.forEach((u) => {
      const href = u.getAttribute('href') || '';
      const baseMatch = href.match(/^#(?:vfd(?:8|16|24|32)-)?(ic-[a-z-]+)$/);
      if (!baseMatch) return;
      const baseId = baseMatch[1];
      const desired = isVfd ? resolveVfdTarget(u, baseId) : `#${baseId}`;
      if (href !== desired) u.setAttribute('href', desired);
    });
  }

